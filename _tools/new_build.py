def main():
    sel = json.load(open(os.path.join(HERE, "new_selection.json")))["selection"]
    src = open(DATA, encoding="utf-8").read()
    work = json.loads(src.split("export const WORK = ", 1)[1].rstrip().rstrip(";"))
    new_ids = {slug(b[1]) for b in BRANDS}
    work = [b for b in work if b["id"] not in new_ids]

    for key, name, industry, tags, desc, excl, videos, after in BRANDS:
        s = slug(name); d = os.path.join(OUT, s)
        if os.path.isdir(d): shutil.rmtree(d)
        os.makedirs(d)
        items = []
        for i, it in enumerate(sel.get(key, [])):
            if i in excl: continue
            n = len(items) + 1
            im = open_rgb(it["path"])
            w, h = save_webp(im, os.path.join(d, f"{n:02d}.webp"), 1800, 82)
            save_webp(im, os.path.join(d, f"{n:02d}-t.webp"), 720, 74)
            items.append({"type": "img", "src": f"assets/work/{s}/{n:02d}.webp",
                          "thumb": f"assets/work/{s}/{n:02d}-t.webp", "w": w, "h": h})
        vi = 0
        for v in videos:
            vi += 1
            res = build_video(os.path.join(ROOT, v), os.path.join(d, f"v{vi}.mp4"), os.path.join(d, f"v{vi}.webp"))
            if not res: print("video fail", v); vi -= 1; continue
            w, h, length = res
            vid = {"type": "vid", "src": f"assets/work/{s}/v{vi}.mp4", "thumb": f"assets/work/{s}/v{vi}.webp", "w": w, "h": h, "len": length}
            # video-only brands keep their order; otherwise spread videos through the images
            items.insert(len(items) if not sel.get(key) else min(len(items), 2 + (vi - 1) * 4), vid)
        pos = next((i + 1 for i, b in enumerate(work) if b["id"] == after), len(work))
        work.insert(pos, {"id": s, "name": name, "industry": industry, "tags": tags, "desc": desc, "items": items})
        print(f"{name}: {len(items) - vi} img, {vi} vid", flush=True)

    js = "/* generated by build_assets.py + new_build.py */\nexport const WORK = " + json.dumps(work, ensure_ascii=False, indent=1) + ";\n"
    open(DATA, "w", encoding="utf-8").write(js)
    print(len(work), "brands,", sum(len(b["items"]) for b in work), "pieces")

if __name__ == "__main__":
    main()
